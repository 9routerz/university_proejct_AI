// AI Agent page: join, chat, timer and score
const $ = (id) => document.getElementById(id);
const CSRF = document.querySelector('meta[name="csrf-token"]').content;
const HAS_SESSION = document.currentScript.dataset.hasSession === '1';
const TOTAL_SECONDS = 3600;
let secondsLeft = 0;
let timerHandle = null;
let models = [];          // [{id, label, note}] from the backend
let defaultModel = '';

async function api(action, body) {
  const res = await fetch('api.php?action=' + action, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': CSRF },
    body: JSON.stringify(body || {}),
  });
  const data = await res.json().catch(() => ({ detail: 'Bad reply from server.' }));
  if (!res.ok) throw new Error(data.detail || 'Request failed.');
  return data;
}

function show(id) {
  ['join', 'chat', 'result'].forEach((s) => $(s).classList.toggle('hidden', s !== id));
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Plain text with `code` and **bold** (everything escaped first)
function inline(text) {
  return esc(text.replace(/^\n+|\n+$/g, ''))
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')
    .replace(/\n/g, '<br>');
}

function block(kind, title, body, copy) {
  const btn = copy ? '<button class="copy-btn" type="button">Copy</button>' : '';
  return '<div class="block ' + kind + '"><div class="block-head"><span class="tag-dot">' + title + '</span>' + btn + '</div>' + body + '</div>';
}

// Agent replies arrive as markdown: ```python code```, **Output:** ```text```, ⚠️ **Error:** ```text```.
// Turn each part into a labelled card. Returns { html, hasBlocks }.
function render(text) {
  const parts = String(text || '').replace(/📊 \*\*Plot generated\*\* \*\(see above\)\*/g, '').split(/```(\w*)\n?([\s\S]*?)```/g);
  let html = '', label = '', hasBlocks = false;
  for (let i = 0; i < parts.length; i += 3) {
    let plain = parts[i];
    if (/\*\*Output:\*\*\s*$/.test(plain)) { label = 'output'; plain = plain.replace(/\*\*Output:\*\*\s*$/, ''); }
    else if (/(⚠️\s*)?\*\*Error:\*\*\s*$/.test(plain)) { label = 'error'; plain = plain.replace(/(⚠️\s*)?\*\*Error:\*\*\s*$/, ''); }
    if (plain.trim()) html += '<div>' + inline(plain) + '</div>';
    if (i + 2 < parts.length) {
      hasBlocks = true;
      const lang = parts[i + 1], code = esc(parts[i + 2].replace(/\s+$/, ''));
      if (lang === 'python') html += block('code', 'Python code', '<pre><code>' + code + '</code></pre>', true);
      else if (label === 'error') html += block('error', 'Error', '<pre>' + code + '</pre>');
      else html += block('output', 'Output', '<pre>' + code + '</pre>');
      label = '';
    }
  }
  return { html, hasBlocks };
}

// ── AI model picker ──────────────────────────────────────────────────────
const modelLabel = (id) => (models.find((m) => m.id === id) || {}).label || id;

function storedModel() {
  try { return localStorage.getItem('dscomp-model') || ''; } catch (e) { return ''; }
}

function updateModelNote() {
  const m = models.find((x) => x.id === $('model-select').value);
  $('model-note').textContent = m ? m.note : '';
}

async function loadModels() {
  try {
    const data = await api('models');
    models = data.models || [];
    defaultModel = data.default || (models[0] && models[0].id) || '';
    const select = $('model-select');
    select.innerHTML = '';
    models.forEach((m) => {
      const opt = document.createElement('option');
      opt.value = m.id;
      opt.textContent = m.label + (m.id === defaultModel ? ' (default)' : '');
      select.appendChild(opt);
    });
    const saved = storedModel();
    select.value = models.some((m) => m.id === saved) ? saved : defaultModel;
    updateModelNote();
  } catch (e) {
    // Keep the built-in default option; the backend uses its default model
  }
}

$('model-select').addEventListener('change', () => {
  updateModelNote();
  try { localStorage.setItem('dscomp-model', $('model-select').value); } catch (e) { /* storage blocked */ }
});

function addMessage(role, text, imageB64, modelUsed) {
  const row = document.createElement('div');
  row.className = 'msg ' + role;
  const who = document.createElement('div');
  who.className = 'who';
  who.textContent = role === 'user' ? ($('avatar').textContent || 'U') : 'AI';
  const bubble = document.createElement('div');
  bubble.className = 'bubble';
  if (role === 'user') {
    bubble.innerHTML = inline(text);
  } else {
    const r = render(text);
    bubble.innerHTML = r.html;
    if (!r.hasBlocks && !imageB64) row.classList.add('plain');
  }
  if (imageB64) {
    bubble.insertAdjacentHTML('beforeend', block('chart', 'Chart', ''));
    const img = document.createElement('img');
    img.src = 'data:image/png;base64,' + imageB64;
    img.alt = 'Chart generated by the agent';
    bubble.lastElementChild.appendChild(img);
  }
  if (modelUsed) {
    const badge = document.createElement('div');
    badge.className = 'model-badge';
    badge.textContent = 'Answered by ' + modelLabel(modelUsed);
    bubble.appendChild(badge);
  }
  row.append(who, bubble);
  $('messages').appendChild(row);
  $('messages').scrollTop = $('messages').scrollHeight;
  return row;
}

function addTyping() {
  const row = addMessage('assistant', '');
  row.querySelector('.bubble').innerHTML = '<span class="typing"><i></i><i></i><i></i></span>';
  return row;
}

function setUser(name) {
  $('who').textContent = name;
  $('avatar').textContent = (name.trim()[0] || '?').toUpperCase();
}

function startTimer(seconds) {
  secondsLeft = seconds;
  clearInterval(timerHandle);
  const tick = () => {
    const m = Math.floor(secondsLeft / 60), s = secondsLeft % 60;
    $('timer').textContent = String(m).padStart(2, '0') + ':' + String(s).padStart(2, '0');
    $('timer').classList.toggle('low', secondsLeft <= 300);
    $('timer-bar').classList.toggle('low', secondsLeft <= 300);
    $('timer-bar').style.width = Math.max(0, (secondsLeft / TOTAL_SECONDS) * 100) + '%';
    if (secondsLeft <= 0) {
      clearInterval(timerHandle);
      $('send-btn').disabled = true;
      $('message').disabled = true;
      addMessage('assistant', '⏰ Time is up! Click **Get my score** to see your result.');
    }
    secondsLeft = Math.max(0, secondsLeft - 1);
  };
  tick();
  timerHandle = setInterval(tick, 1000);
}

async function refreshStatus() {
  try {
    const st = await api('status');
    $('actions').textContent = st.action_count;
    setUser(st.participant_name);
    startTimer(st.time_remaining_seconds);
    return true;
  } catch (e) {
    return false;
  }
}

$('join-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  $('join-error').textContent = '';
  const btn = $('join-btn');
  btn.disabled = true;
  btn.innerHTML = '<span class="spinner"></span> Preparing your sandbox…';
  try {
    const name = $('name').value.trim();
    const code = $('code') ? $('code').value : '';
    const data = await api('start', { name, code });
    setUser(name);
    show('chat');
    loadModels();
    addMessage('assistant', data.message);
    startTimer(data.time_limit_seconds);
    $('message').focus();
  } catch (err) {
    $('join-error').textContent = err.message;
  } finally {
    btn.disabled = false;
    btn.innerHTML = 'Begin session <span aria-hidden="true">→</span>';
  }
});

$('chat-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  const text = $('message').value.trim();
  if (!text || $('send-btn').disabled) return;
  $('message').value = '';
  autosize();
  addMessage('user', text);
  const pending = addTyping();
  $('send-btn').disabled = true;
  try {
    const data = await api('chat', { message: text, model: $('model-select').value });
    pending.remove();
    addMessage('assistant', data.response, data.image_base64, data.model_used);
    secondsLeft = data.time_remaining_seconds;
    if (data.intent === 'code') $('actions').textContent = Number($('actions').textContent) + 1;
  } catch (err) {
    pending.remove();
    addMessage('assistant', '⚠️ ' + err.message);
  } finally {
    if (secondsLeft > 0) $('send-btn').disabled = false;
    $('message').focus();
  }
});

// On a computer Enter sends and Shift+Enter makes a new line.
// On a touch screen Enter makes a new line and the Send button sends (no accidental sends).
const isTouch = window.matchMedia('(pointer: coarse)').matches;
if (isTouch) {
  $('message').setAttribute('enterkeyhint', 'enter');
  const hint = document.querySelector('.composer-hint');
  if (hint) hint.textContent = 'Tap Send to send';
}

// The box grows with the text
function autosize() {
  const t = $('message');
  t.style.height = '50px';
  t.style.height = Math.min(t.scrollHeight, 160) + 'px';
}
$('message').addEventListener('input', autosize);
$('message').addEventListener('keydown', (e) => {
  if (e.key === 'Enter' && !e.shiftKey && !isTouch) { e.preventDefault(); $('chat-form').requestSubmit(); }
});

// Jump-to-latest button appears when you scroll up through older messages
const messagesBox = $('messages');
const nearBottom = () => messagesBox.scrollHeight - messagesBox.scrollTop - messagesBox.clientHeight < 120;
messagesBox.addEventListener('scroll', () => $('scroll-down').classList.toggle('hidden', nearBottom()), { passive: true });
$('scroll-down').addEventListener('click', () => {
  messagesBox.scrollTo({ top: messagesBox.scrollHeight, behavior: 'smooth' });
});

// When the phone keyboard opens, keep the latest message in view
if (window.visualViewport) {
  let wasNearBottom = true;
  messagesBox.addEventListener('scroll', () => { wasNearBottom = nearBottom(); }, { passive: true });
  window.visualViewport.addEventListener('resize', () => {
    if (wasNearBottom) messagesBox.scrollTop = messagesBox.scrollHeight;
  });
}

// Copy button on code cards
$('messages').addEventListener('click', async (e) => {
  const btn = e.target.closest('.copy-btn');
  if (!btn) return;
  const code = btn.closest('.block').querySelector('pre').innerText;
  try { await navigator.clipboard.writeText(code); btn.textContent = 'Copied'; }
  catch (err) { btn.textContent = 'Failed'; }
  setTimeout(() => { btn.textContent = 'Copy'; }, 1200);
});

// Quick prompts (sidebar on computers, a swipeable row on phones) fill the message box
['side-chips', 'mobile-chips'].forEach((id) => {
  $(id).addEventListener('click', (e) => {
    const chip = e.target.closest('.chip');
    if (!chip) return;
    $('message').value = chip.textContent;
    autosize();
    $('message').focus();
  });
});

$('score-btn').addEventListener('click', async () => {
  if (!confirm('You can only get your score once and your session will end. Continue?')) return;
  const btn = $('score-btn');
  btn.disabled = true;
  btn.innerHTML = '<span class="spinner"></span> Evaluating…';
  try {
    const data = await api('score');
    clearInterval(timerHandle);
    $('score-value').textContent = data.score;
    $('score-ring').style.setProperty('--p', Math.max(0, Math.min(100, data.score)));
    $('score-breakdown').textContent = data.breakdown;
    $('score-feedback').textContent = data.feedback;
    show('result');
  } catch (err) {
    addMessage('assistant', '⚠️ ' + err.message);
    btn.disabled = false;
    btn.innerHTML = '<span class="long">Get my score</span><span class="short">Score</span>';
  }
});

// Page reload: resume the running session
if (HAS_SESSION) {
  refreshStatus().then((ok) => {
    if (ok) { loadModels(); addMessage('assistant', 'Welcome back! Your session is still running. The dataset is loaded as `df`.'); }
    else show('join');
  });
}
